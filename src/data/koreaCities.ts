/**
 * 공개 규칙(rules.ts)에 따라 모든 161개 도시의 지구(District), 시민 구성, 20개 렌즈 지표, 6대 Civ 산출량 산출
 */
export function buildComputedCities(sourceRaws: CityRawRecord[] = RAW_CITIES): CityComputed[] {
  const totalWorkersSum = sourceRaws.reduce((s, c) => s + c.totalWorkers, 0) || 1;
  const natShares = {} as Record<IndustryKey, number>;
  for (const key of INDUSTRY_KEYS) {
    const weighted = sourceRaws.reduce((s, c) => s + c.totalWorkers * (c.shares[key] / 100), 0);
    natShares[key] = (weighted / totalWorkersSum) * 100;
  }

  return sourceRaws.map((city) => {
    const pt = latLonToKm(city.lat, city.lon);
    // 1인당 GRDP (만원) = (억원 * 10000만원) / 인구
    const grdpPerCapitaManwon = Math.round((city.grdpBillionKrw * 10000) / Math.max(1, city.population));

    // 7개 산업별 LQ 및 "N명 중 1명" 계산
    const citizens: CitizenBreakdown[] = INDUSTRY_KEYS.map((key) => {
      const sharePct = city.shares[key];
      const nationalSharePct = natShares[key];
      const workers = Math.round(city.totalWorkers * (sharePct / 100));
      const lq = nationalSharePct > 0 ? sharePct / nationalSharePct : 0;
      const oneInN = sharePct > 0.05 ? Math.max(1, Math.round(100 / sharePct)) : 999;
      const nationalOneInN =
        nationalSharePct > 0.05 ? Math.max(1, Math.round(100 / nationalSharePct)) : 999;

      return {
        industry: key,
        labelKo: INDUSTRY_META[key].nameKo,
        workers,
        sharePct,
        nationalSharePct: Number(nationalSharePct.toFixed(1)),
        oneInN,
        nationalOneInN,
        lq: Number(lq.toFixed(2)),
      };
    });

    // 지구(District) 선정 규칙: LQ >= 1.5 && 종사자 >= 5,000명 (운수·창고업은 무역항 보유 도시만 Harbor 부여)
    const eligibleDistricts: ComputedDistrict[] = [];
    for (const c of citizens) {
      const meta = INDUSTRY_META[c.industry];
      if (meta.requiresTradePort && !city.hasTradePort) continue;
      if (
        c.lq >= CIV_RULES.district.minLocationQuotient &&
        c.workers >= CIV_RULES.district.minWorkers
      ) {
        eligibleDistricts.push({
          type: meta.district,
          industry: c.industry,
          lq: c.lq,
          workers: c.workers,
          sharePct: c.sharePct,
        });
      }
    }

    eligibleDistricts.sort((a, b) => b.lq - a.lq);
    const districts = eligibleDistricts.slice(0, CIV_RULES.district.maxDistrictsPerCity);

    const mfgWorkers = Math.round(city.totalWorkers * (city.shares.manufacturing / 100));
    const agriWorkers = Math.round(city.totalWorkers * (city.shares.agriculture / 100));
    const ictWorkers = Math.round(city.totalWorkers * (city.shares.ictScience / 100));
    const hospWorkers = Math.round(city.totalWorkers * (city.shares.hospitality / 100));

    // 6대 추가 사회경제·인프라 지표 (실측 앵커 우선 + 시도/구조 회귀 보정)
    const anchor = CITY_SOCIO_ANCHORS[city.id];
    const isCapital =
      city.province === 'seoul' || city.province === 'gyeonggi' || city.province === 'incheon';

    const avgIncomeManwon =
      anchor?.income ??
      Math.round(
        Math.max(
          3050,
          Math.min(
            6800,
            3280 +
              Math.min(1800, (grdpPerCapitaManwon - 2600) * 0.19) +
              city.shares.ictScience * 42 +
              city.shares.finance * 65 +
              city.shares.manufacturing * 11 -
              Math.max(0, city.agingRate - 22) * 18 +
              (isCapital ? 260 : 0)
          )
        )
      );

    const collegeDegreePct =
      anchor?.degree ??
      Number(
        Math.max(
          21.5,
          Math.min(
            68.5,
            51.0 -
              (city.agingRate - 17) * 0.78 +
              city.shares.ictScience * 0.55 +
              Math.min(6, Math.log10(Math.max(10, city.universityRd100M)) * 1.4) +
              (isCapital ? 3.2 : 0) -
              (city.tier === 4 ? 3.5 : 0)
          )
        ).toFixed(1)
      );

    const faithRatePct =
      anchor?.faith ??
      Number(
        Math.max(
          34.0,
          Math.min(
            58.5,
            PROVINCE_FAITH_BASE[city.province] +
              (city.shares.hospitality > 18 ? 2.4 : 0) +
              (city.agingRate > 32 ? 1.8 : -0.6) +
              (city.tier === 1 ? 1.2 : 0)
          )
        ).toFixed(1)
      );

    const lifeExpectancy =
      anchor?.life ??
      Number(
        Math.max(
          80.6,
          Math.min(
            86.2,
            83.5 +
              (avgIncomeManwon - 4100) / 1450 +
              (collegeDegreePct - 42) * 0.025 +
              (isCapital ? 0.55 : 0) -
              Math.max(0, city.agingRate - 30) * 0.04
          )
        ).toFixed(1)
      );

    const housingPriceManwon =
      anchor?.housing ??
      Math.round(
        Math.max(
          460,
          Math.min(
            5200,
            PROVINCE_HOUSING_BASE[city.province] *
              (city.tier === 1 ? 1.05 : city.tier === 2 ? 0.96 : city.tier === 3 ? 0.78 : 0.62) +
              (avgIncomeManwon - 4000) * 0.24 -
              Math.max(0, city.agingRate - 24) * 12
          )
        )
      );

    const freightVolumeMt =
      anchor?.freight ??
      Number(
        Math.max(
          1.2,
          (city.totalWorkers * (city.shares.logistics * 0.014 + city.shares.manufacturing * 0.005)) /
            1000 +
            (city.hasTradePort ? 22 : 0) +
            city.grdpBillionKrw / 18000
        ).toFixed(1)
      );

    const policyCard = deriveCityPolicyCard({
      districts,
      citizens,
      shares: city.shares,
      universityRd100M: city.universityRd100M,
      hasTradePort: city.hasTradePort,
      freightVolumeMt,
    });

    return {
      ...city,
      provinceName: PROVINCE_META[city.province].name,
      grdpPerCapitaManwon,
      avgIncomeManwon,
      collegeDegreePct,
      faithRatePct,
      lifeExpectancy,
      housingPriceManwon,
      freightVolumeMt,
      areaKm2: 100, // 격자 생성 후 실제 육지 타일 면적으로 갱신됨
      populationDensity: Math.round(city.population / 100),
      districts,
      policyCard,
      culturalSiteCount: 0, // 격자·시설 매핑 후 공간 집계로 갱신됨
      cultureScore: Math.round(Math.min(100, city.shares.hospitality * 1.4)),
      citizens: [...citizens].sort((a, b) => b.sharePct - a.sharePct),
      yields: {
        gold: Number((city.grdpBillionKrw / 10000).toFixed(2)), // 조원
        production: Number((mfgWorkers / 1000).toFixed(1)), // 천명
        food: Math.round(agriWorkers / 250 + city.shares.agriculture * 1.5),
        science: Math.round(city.universityRd100M / 120 + ictWorkers / 1800),
        culture: Math.round(hospWorkers / 1400 + city.shares.hospitality * 1.4),
        faith: Math.round(faithRatePct * 0.9 + (city.population / 100000) * 1.2),
      },
      hexCount: 0,
      centerX: pt.x,
      centerY: pt.y,
    };
  });
}
